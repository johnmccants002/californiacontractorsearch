-- Centralized database ranking primitive for the production search adapter.
create or replace function public.search_license_ids(search_query text, result_limit integer default 50)
returns table (license_id bigint, relevance_score double precision)
language sql
stable
set search_path = pg_catalog
as $$
  with query as (
    select
      public.normalize_search_text(search_query) as normalized,
      regexp_replace(public.normalize_search_text(search_query), '\s', '', 'g') as compact,
      public.normalize_business_name(search_query) as business
  )
  select
    l.id,
    (
      case when l.license_number = q.compact then 1000 else 0 end +
      case when l.business_name_normalized = q.business then 800
           when l.business_name_normalized like q.business || '%' then 650 else 0 end +
      coalesce(extensions.similarity(l.business_name_normalized, q.business) * 400, 0) +
      case when lower(l.city) = q.normalized then 450 else 0 end +
      case when l.zip = q.compact then 500 else 0 end +
      case when exists (select 1 from public.personnel p where p.license_id = l.id and p.full_name_normalized = q.normalized) then 600 else 0 end +
      case when exists (
        select 1 from public.personnel p
        where p.license_id = l.id and extensions.similarity(p.full_name_normalized, q.normalized) >= 0.35
      ) then 300 else 0 end +
      case when exists (
        select 1 from public.license_classifications lc
        join public.classifications c on c.id = lc.classification_id
        where lc.license_id = l.id
          and (c.code = q.compact or public.normalize_search_text(c.name || ' ' || array_to_string(c.aliases, ' ')) like '%' || q.normalized || '%')
      ) then 550 else 0 end +
      case when l.license_status = 'ACTIVE' then 10 else 0 end
    )::double precision as relevance_score
  from public.licenses l cross join query q
  where q.normalized <> '' and (
    l.license_number = q.compact
    or l.business_name_normalized like '%' || q.business || '%'
    or extensions.similarity(l.business_name_normalized, q.business) >= 0.25
    or lower(l.city) like '%' || q.normalized || '%'
    or l.zip = q.compact
    or exists (select 1 from public.personnel p where p.license_id = l.id and (p.full_name_normalized like '%' || q.normalized || '%' or extensions.similarity(p.full_name_normalized, q.normalized) >= 0.35))
    or exists (
      select 1 from public.license_classifications lc join public.classifications c on c.id = lc.classification_id
      where lc.license_id = l.id and (c.code = q.compact or public.normalize_search_text(c.name || ' ' || array_to_string(c.aliases, ' ')) like '%' || q.normalized || '%')
    )
  )
  order by relevance_score desc, l.business_name asc
  limit least(greatest(result_limit, 1), 100);
$$;

