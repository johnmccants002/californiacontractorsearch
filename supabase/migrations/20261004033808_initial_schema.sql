-- California Contractor Search initial schema
-- Source values are preserved; normalized values live in separate columns.

create schema if not exists extensions;
create extension if not exists pg_trgm with schema extensions;

create or replace function public.normalize_search_text(input text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog
as $$
  select trim(regexp_replace(regexp_replace(lower(coalesce(input, '')), '([a-z])\s*-\s*([0-9])', '\1\2', 'g'), '[^a-z0-9]+', ' ', 'g'));
$$;

create or replace function public.normalize_business_name(input text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog
as $$
  select trim(regexp_replace(regexp_replace(public.normalize_search_text(input), '^the\s+', ''), '\s+(llc|inc|incorporated|corp|corporation|company|co)$', ''));
$$;

create table public.licenses (
  id bigint generated by default as identity primary key,
  license_number text not null unique,
  business_name text not null,
  business_name_normalized text not null default '',
  license_status text not null check (license_status in ('ACTIVE', 'EXPIRED', 'SUSPENDED', 'INACTIVE')),
  license_type text,
  issue_date date,
  expiration_date date,
  address_line_1 text,
  address_line_2 text,
  city text,
  state text not null default 'CA',
  zip text,
  phone text,
  entity_type text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  source_updated_at timestamptz
);

create table public.classifications (
  id bigint generated by default as identity primary key,
  code text not null unique check (code = lower(regexp_replace(code, '[^a-zA-Z0-9]', '', 'g'))),
  name text not null,
  slug text not null unique,
  description text,
  aliases text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.license_classifications (
  id bigint generated by default as identity primary key,
  license_id bigint not null references public.licenses(id) on delete cascade,
  classification_id bigint not null references public.classifications(id) on delete cascade,
  unique (license_id, classification_id)
);

create table public.personnel (
  id bigint generated by default as identity primary key,
  license_id bigint not null references public.licenses(id) on delete cascade,
  first_name text not null,
  middle_name text,
  last_name text not null,
  full_name text not null,
  full_name_normalized text not null default '',
  role text,
  association_date date,
  disassociation_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.bonds (
  id bigint generated by default as identity primary key,
  license_id bigint not null references public.licenses(id) on delete cascade,
  bond_type text not null,
  bond_company text,
  bond_number text,
  bond_amount numeric(12, 2),
  effective_date date,
  cancellation_date date,
  unique (license_id, bond_type, bond_number)
);

create table public.workers_comp (
  id bigint generated by default as identity primary key,
  license_id bigint not null references public.licenses(id) on delete cascade,
  carrier text,
  policy_number text,
  effective_date date,
  expiration_date date,
  exemption boolean not null default false,
  unique (license_id, policy_number)
);

create or replace function public.set_normalized_fields()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  if tg_table_name = 'licenses' then
    new.business_name_normalized := public.normalize_business_name(new.business_name);
  elsif tg_table_name = 'personnel' then
    new.full_name_normalized := public.normalize_search_text(new.full_name);
  end if;
  return new;
end;
$$;

create trigger licenses_normalize_before_write before insert or update of business_name on public.licenses
for each row execute function public.set_normalized_fields();
create trigger personnel_normalize_before_write before insert or update of full_name on public.personnel
for each row execute function public.set_normalized_fields();

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin new.updated_at := now(); return new; end;
$$;

create trigger licenses_set_updated_at before update on public.licenses for each row execute function public.set_updated_at();
create trigger classifications_set_updated_at before update on public.classifications for each row execute function public.set_updated_at();
create trigger personnel_set_updated_at before update on public.personnel for each row execute function public.set_updated_at();

